"""Where the demos' inputs and outputs live, resolved relative to this file.

The counterpart to `lit_search/paths.py`, and the same three-layer rule:

    data/demos/<demo>/observations.csv   frozen evidence. NEVER written by code here.
    data/raw/                            Census and contact-matrix inputs, each frozen
                                         with its provenance the first time it is needed
                                         and only ever read after that.
    results/demos/runs/<demo>/seed<N>/   generated by `flu/run_season.py` and
                                         `demo-covid.ipynb`. Large, gitignored.
    results/demos/tables/                generated. Always safe to delete.
    results/demos/figures/              generated. Always safe to delete.

**`observations.csv` is in `data/`, not beside the runs, and that is the point.** CDC's
preliminary datasets are revised weekly, so re-fetching them gives different numbers; the
frozen copy is evidence that cannot be regenerated, and it sits with the other evidence.
Everything under `results/` can be deleted and rebuilt.

The run outputs are ~1 GB and are **not carried by git** (see the repository `.gitignore`).
They are regenerated by `scripts/run-demos.sh` or fetched from the archive; a fixed seed
reproduces them byte for byte on the same platform.
"""

from pathlib import Path

# .../analysis/src/manuscript_analysis/demos/paths.py -> the repository root.
ROOT = Path(__file__).resolve().parents[4]

DATA = ROOT / "data" / "demos"
RAW = ROOT / "data" / "raw"
"""External inputs the models read, frozen so a build needs no Census key and no download."""
RESULTS = ROOT / "results"
RUNS = RESULTS / "demos" / "runs"
TABLES = RESULTS / "demos" / "tables"
FIGURES = RESULTS / "demos" / "figures"

MANIFEST = RESULTS / "demos" / "MANIFEST.sha256"
"""Checksums of the run outputs, so a regenerated ensemble can be held to the one the
manuscript used. See `scripts/check.sh`."""


def observations(demo: str) -> Path:
    """The frozen observations for `"flu"` or `"covid"`."""
    return DATA / demo / "observations.csv"


def runs(demo: str, seed: int = 0) -> Path:
    """The run outputs for one demo at one ensemble seed, one folder per model.

    Folders are named for the model, at both seeds. In the working folder the seed-1 flu
    runs lived under `sensitivity/` with run-specific names, which is why
    `flu.evaluation.load` needed a `folders` mapping; naming them consistently here made
    that argument unnecessary.
    """
    return RUNS / demo / f"seed{seed}"
