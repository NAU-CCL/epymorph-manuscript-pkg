"""Checksums of the run outputs, so a regenerated ensemble can be held to the real one.

The ensembles are ~1 GB and git does not carry them (see `paths`), so this file is how
the repository states what the manuscript's numbers were computed from. It is small, it
is in git, and `--check` says whether what is on disk is the same thing.

**`run.json` is excluded, deliberately.** It records `elapsed_seconds`, which differs
every run, so including it would make the check fail every time and therefore mean
nothing. Everything that carries a number the analysis reads is covered: `fit.csv`,
`params.csv`, and every file under `forecasts/`.

Determinism was verified on 2026-09-22: re-running COVID's `state` model at seed 0
reproduced `fit.csv`, `params.csv` and all 24 forecast files byte for byte. That was one
model on one machine with one set of pinned versions, so this check is expected to pass
on the platform that produced the runs and **not** across platforms: floating-point
ensembles rarely reproduce bit-exactly on different hardware or BLAS. On a different
platform, compare `results/demos/tables/` instead, which is what the paper's claims rest
on.

Usage:

    python -m manuscript_analysis.demos.manifest --write
    python -m manuscript_analysis.demos.manifest --check
"""

import argparse
import hashlib
from pathlib import Path

from manuscript_analysis.demos import paths

EXCLUDED = {"run.json"}
"""Files whose contents legitimately differ between identical runs."""

CHUNK = 1 << 20


def digest(path: Path) -> str:
    """SHA-256 of one file, read in chunks so a 114 MB `params.csv` is not held in RAM."""
    hasher = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(CHUNK):
            hasher.update(chunk)
    return hasher.hexdigest()


def entries() -> list[tuple[str, str]]:
    """`(relative path, digest)` for every run output, sorted, so the file is stable."""
    if not paths.RUNS.exists():
        raise SystemExit(
            f"no run outputs at {paths.RUNS}. Run scripts/run-demos.sh, or fetch the "
            "archived outputs; see results/demos/README.md."
        )
    found = []
    for path in sorted(paths.RUNS.rglob("*")):
        if path.is_file() and path.name not in EXCLUDED and not path.name.startswith("."):
            found.append((str(path.relative_to(paths.RUNS)), digest(path)))
    return found


def render(found: list[tuple[str, str]]) -> str:
    header = [
        "# SHA-256 of the demo run outputs, relative to results/demos/runs/.",
        "# Generated by: python -m manuscript_analysis.demos.manifest --write",
        f"# {len(found)} files. run.json is excluded: it records elapsed time.",
    ]
    body = [f"{value}  {name}" for name, value in found]
    return "\n".join(header + body) + "\n"


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="write the manifest")
    group.add_argument("--check", action="store_true", help="verify against it")
    args = parser.parse_args(argv)

    found = entries()

    if args.write:
        paths.MANIFEST.parent.mkdir(parents=True, exist_ok=True)
        paths.MANIFEST.write_text(render(found))
        total = sum(
            (paths.RUNS / name).stat().st_size for name, _ in found
        )
        print(f"wrote {paths.MANIFEST}")
        print(f"  {len(found)} files, {total / 1e9:.2f} GB")
        return

    if not paths.MANIFEST.exists():
        raise SystemExit(f"no manifest at {paths.MANIFEST}; write one first")

    recorded = {}
    for line in paths.MANIFEST.read_text().splitlines():
        if line.startswith("#") or not line.strip():
            continue
        value, _, name = line.partition("  ")
        recorded[name] = value
    current = dict((name, value) for name, value in found)

    missing = sorted(set(recorded) - set(current))
    added = sorted(set(current) - set(recorded))
    changed = sorted(
        name for name in set(recorded) & set(current)
        if recorded[name] != current[name]
    )
    for label, names in (("missing", missing), ("unexpected", added), ("changed", changed)):
        for name in names[:10]:
            print(f"  {label}: {name}")
        if len(names) > 10:
            print(f"  ... and {len(names) - 10} more {label}")
    if missing or added or changed:
        raise SystemExit(
            f"{len(missing)} missing, {len(added)} unexpected, {len(changed)} changed. "
            "On a different platform this is expected; compare results/demos/tables/."
        )
    print(f"all {len(found)} run files match the manifest")


if __name__ == "__main__":
    main()
